#!/usr/bin/env python3
"""Export the SVG brand sources to native vectors and legacy PNG fallbacks.

Requires rsvg-convert (librsvg) for legacy PNGs only. Modern Android and
Flutter render vector paths directly; do not regenerate them from PNGs.
Run from the repository root: python tool/generate_brand_assets.py
"""
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / 'android/app/src/main/res'
ART = ROOT / 'assets/images'
SVG = '{http://www.w3.org/2000/svg}'
LIGHT_BACKGROUND = '#EEEDEF'
DARK_BACKGROUND = '#121315'


def render(source, output, size):
    output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['rsvg-convert', '--width', str(size), '--height', str(size),
                    '--output', str(output)], input=source.encode(), check=True)


def native_vector(source, output, monochrome=False):
    tree = ET.fromstring(source)
    gradients = {g.attrib['id']: g for g in tree.iter(SVG + 'linearGradient')}
    vector = ET.Element('vector', {
        'xmlns:android': 'http://schemas.android.com/apk/res/android',
        'xmlns:aapt': 'http://schemas.android.com/aapt',
        'android:width': '108dp', 'android:height': '108dp',
        'android:viewportWidth': '1024', 'android:viewportHeight': '1024',
    })
    for facet in tree.iter(SVG + 'path'):
        path = ET.SubElement(vector, 'path', {'android:pathData': facet.attrib['d']})
        if monochrome:
            path.set('android:fillColor', '#FFFFFFFF')
            continue
        gradient = gradients[facet.attrib['fill'][5:-1]]
        fill = ET.SubElement(path, 'aapt:attr', {'name': 'android:fillColor'})
        native = ET.SubElement(fill, 'gradient', {
            'android:type': 'linear',
            **{'android:' + target: gradient.attrib[source]
               for source, target in [('x1', 'startX'), ('y1', 'startY'),
                                      ('x2', 'endX'), ('y2', 'endY')]},
        })
        stops = list(gradient)
        for index, stop in enumerate(stops):
            ET.SubElement(native, 'item', {
                'android:color': stop.attrib['stop-color'],
                'android:offset': stop.attrib.get('offset', '0' if index == 0 else '1'),
            })
    ET.indent(vector, space='    ')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('<!-- Generated by tool/generate_brand_assets.py; edit the SVG sources. -->\n'
                      + ET.tostring(vector, encoding='unicode') + '\n')


source = (ART / 'brand_mark.svg').read_text()
light = (ART / 'brand_mark_light.svg').read_text()
mono_tree = ET.fromstring(source)
mono_tree.remove(mono_tree.find(SVG + 'defs'))
for facet in mono_tree.iter(SVG + 'path'):
    facet.set('fill', '#ffffff')
mono = ET.tostring(mono_tree, encoding='unicode')
# Kept for legacy tools and consumers; the app itself uses SVG/VectorDrawable.
for name, artwork in [('brand_mark', source), ('brand_mark_light', light), ('brand_mark_mono', mono)]:
    render(artwork, ART / f'{name}.png', 1024)

native_vector(light, RES / 'drawable-anydpi/ic_launcher_foreground.xml')
native_vector(source, RES / 'drawable-night-anydpi/ic_launcher_foreground.xml')
native_vector(source, RES / 'drawable-anydpi/ic_launcher_monochrome.xml', monochrome=True)

for palette, artwork, background in [('', light, LIGHT_BACKGROUND), ('-night', source, DARK_BACKGROUND)]:
    # Compose with an XML element rather than relying on source comments.
    tree = ET.fromstring(artwork)
    tree.insert(0, ET.Element(SVG + 'rect', {'width': '1024', 'height': '1024', 'fill': background}))
    composed = ET.tostring(tree, encoding='unicode')
    if not palette:
        render(composed, ART / 'brand_launcher.png', 1024)
    for density, scale in [('mdpi', 1), ('hdpi', 1.5), ('xhdpi', 2), ('xxhdpi', 3), ('xxxhdpi', 4)]:
        render(composed, RES / f'mipmap{palette}-{density}/ic_launcher.png', round(48 * scale))
        # Remove bitmap layers superseded by resolution-independent vectors.
        if not palette:
            for name in ['ic_launcher_foreground', 'ic_launcher_monochrome']:
                (RES / f'drawable-{density}/{name}.png').unlink(missing_ok=True)
print('Generated light/dark Android vectors and legacy PNG fallbacks')
# Stable, explicitly selected launcher palettes (independent of OS night mode).
for name, art, color in [('light', light, LIGHT_BACKGROUND), ('dark', source, DARK_BACKGROUND), ('black', source, '#000000')]:
    native_vector(art, RES / f'drawable-anydpi/brand_{name}.xml')
    target = RES / f'mipmap-anydpi-v26/launcher_{name}.xml'
    target.write_text(f'''<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/brand_{name}_background" />
    <foreground><inset android:drawable="@drawable/brand_{name}" android:inset="19%" /></foreground>
    <monochrome><inset android:drawable="@drawable/ic_launcher_monochrome" android:inset="19%" /></monochrome>
</adaptive-icon>
''')
    tree = ET.fromstring(art)
    tree.insert(0, ET.Element(SVG + 'rect', {'width':'1024','height':'1024','fill':color}))
    for density, scale in [('mdpi',1),('hdpi',1.5),('xhdpi',2),('xxhdpi',3),('xxxhdpi',4)]:
        render(ET.tostring(tree, encoding='unicode'), RES / f'mipmap-{density}/launcher_{name}.png', round(48*scale))
